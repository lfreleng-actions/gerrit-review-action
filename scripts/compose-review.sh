# Print the 'gerrit review' command line the action sends over SSH.
# Run it with 'bash scripts/compose-review.sh'.
#
# Reads its inputs from the environment, so the calling step never
# interpolates a templated value into shell code:
#
#   VOTE_TYPE               clear, success, failure or cancelled
#   COMMENT_ONLY            'false' applies the votes; any other value
#                           posts the comment alone
#   GERRIT_CHANGE_NUMBER    positive integer
#   GERRIT_PATCHSET_NUMBER  positive integer
#   RUN_URL                 link back to the workflow run
#   WORKFLOW_NAME           github.workflow
#   WORKFLOW_REF            github.workflow_ref
#   REVIEW_MESSAGE          optional text appended to the comment
#   REPORT_ANNOTATIONS      'true' or 'false' (default 'false' when unset)
#   ERROR_ITEMS             errors block items from failed-jobs.py
#   TRAILERS                optional 'Key: value' lines
#
# The comment is made of blocks separated by one blank line, in this
# order, an absent block leaving no gap:
#
#   <STATUS>: <RUN_URL>
#   JOB:     <workflow name> [<workflow file>]
#
#   <REVIEW_MESSAGE>
#
#   ERRORS:
#   - <job name>: <message> ( <job URL> )
#
#   <TRAILERS>
#
# The job line pads 'JOB:' so its value starts in the URL's column,
# and drops the brackets when the workflow file cannot be derived.
# The errors block appears only with REPORT_ANNOTATIONS 'true' and a
# failure or cancelled vote, and shrinks, or goes, to keep the comment
# within MAX_REVIEW_BYTES. The review is tagged
# 'autogenerated:github:<workflow file>', or 'autogenerated:github'
# when the file cannot be derived.
#
# REVIEW_MESSAGE and TRAILERS are each capped at MAX_MESSAGE_BYTES and
# may hold newlines but no other control characters; each trailer
# line must match TRAILER_PATTERN. The comment without its errors
# block must also fit MAX_REVIEW_BYTES. Anything else exits non-zero
# and prints nothing on stdout.
#
# ssh joins its arguments into one string, and Gerrit's SSH daemon
# splits that string again (CommandFactoryProvider.split): blanks
# separate words, quotes group them, and a backslash outside single
# quotes escapes the next character. It expands nothing. The comment
# travels as a single single-quoted word, with each embedded single
# quote written as '\'' (close, escaped quote, reopen). A POSIX shell
# reads that form identically, so the word stays literal whichever of
# the two parses it.

set -euo pipefail
# Byte semantics: the length caps count bytes and the character
# checks below match single bytes.
export LC_ALL=C

readonly MAX_MESSAGE_BYTES=4096
readonly MAX_REVIEW_BYTES=4096
readonly MAX_ERROR_ITEMS=10
readonly TRAILER_PATTERN='^[A-Za-z][A-Za-z0-9-]*: [^[:space:]].*$'
readonly FILE_PATTERN='^[A-Za-z0-9._-]+$'

# C1 controls (U+0080-U+009F) are the UTF-8 byte pairs 0xC2 0x80-0x9F.
readonly c1_lead=$'\xc2'
readonly c1_range=$'[\x80-\x9f]'

fail() {
  # Never echo caller-supplied text: the runner would act on any
  # workflow command embedded in it.
  echo "::error::$*" >&2
  exit 1
}

# Wrap one argument in single quotes for the remote command line.
quote() {
  local escaped="'\\''"
  printf "'%s'" "${1//\'/${escaped}}"
}

# True when $1 holds a control character other than newline.
has_control() {
  [[ "${1//$'\n'/}" == *[[:cntrl:]]* ]] \
    || [[ "$1" == *"${c1_lead}"${c1_range}* ]]
}

# Validate free text ($2, named $1) and print it without trailing
# newlines, such as the one a YAML block scalar ('key: |') adds.
checked_text() {
  local name="$1" text="$2"
  if (( ${#text} > MAX_MESSAGE_BYTES )); then
    fail "Refusing to use ${name}: ${#text} bytes exceeds the" \
      "${MAX_MESSAGE_BYTES}-byte limit"
  fi
  if has_control "${text}"; then
    fail "Refusing to use ${name}: it contains a control character" \
      "other than newline"
  fi
  while [[ "${text}" == *$'\n' ]]; do
    text="${text%$'\n'}"
  done
  printf '%s' "${text}"
}

case "${VOTE_TYPE:-}" in
  clear)
    labels="--label Verified=0 --label Code-Review=0"
    status="STARTED"
    ;;
  success)
    labels="--label Verified=1"
    status="SUCCESS"
    ;;
  failure)
    labels="--label Verified=-1"
    status="FAILURE"
    ;;
  cancelled)
    labels="--label Verified=-1 --label Code-Review=-1"
    status="CANCELLED"
    ;;
  *)
    fail "Unknown vote-type '${VOTE_TYPE:-}':" \
      "expected clear, success, failure or cancelled"
    ;;
esac

# Positive integers only (no leading zeros), so whitespace or
# metacharacters cannot change the meaning of the remote command.
change="${GERRIT_CHANGE_NUMBER:-}"
patchset="${GERRIT_PATCHSET_NUMBER:-}"
if [[ ! "${change}" =~ ^[1-9][0-9]*$ ]]; then
  fail "Refusing to use gerrit-change-number '${change}':" \
    "must be a positive integer"
fi
if [[ ! "${patchset}" =~ ^[1-9][0-9]*$ ]]; then
  fail "Refusing to use gerrit-patchset-number '${patchset}':" \
    "must be a positive integer"
fi

# Default only when unset, so an empty value is refused below.
report_annotations="${REPORT_ANNOTATIONS-false}"
case "${report_annotations}" in
  true | false) ;;
  *) fail "Refusing to use report-annotations: expected true or false" ;;
esac

message="$(checked_text message "${REVIEW_MESSAGE:-}")"
trailers="$(checked_text trailers "${TRAILERS:-}")"
if [[ -n "${trailers}" ]]; then
  while IFS= read -r line; do
    if [[ ! "${line}" =~ ${TRAILER_PATTERN} ]]; then
      fail "Refusing to use trailers: each line must be 'Key: value'"
    fi
  done <<< "${trailers}"
fi

# The workflow file: the base name of the path in WORKFLOW_REF
# ('owner/repo/.github/workflows/verify.yaml@refs/heads/main').
# Cut at the first '@refs/', which the file name cannot hold as it has
# no '/', so an '@' in the file name stays in it and fails the check.
workflow_path="${WORKFLOW_REF:-}"
if [[ "${workflow_path}" == *@refs/* ]]; then
  workflow_path="${workflow_path%%@refs/*}"
else
  workflow_path="${workflow_path%@*}"
fi
workflow_file="${workflow_path##*/}"
if [[ "${workflow_path}" != */* ]] \
  || [[ ! "${workflow_file}" =~ ${FILE_PATTERN} ]]; then
  workflow_file=""
fi

workflow_name="${WORKFLOW_NAME:-}"
workflow_name="${workflow_name//[[:cntrl:]]/}"
workflow_name="${workflow_name//"${c1_lead}"${c1_range}/}"
# A workflow without 'name:' reports its path as its name.
if [[ "${workflow_name}" == .github/workflows/* ]]; then
  workflow_name="${workflow_name##*/}"
  workflow_name="${workflow_name%.*}"
fi
if [[ -z "${workflow_name// /}" ]]; then
  workflow_name="${workflow_file%.*}"
fi
if [[ -z "${workflow_name}" ]]; then
  workflow_name="unknown"
fi

status_line="${status}: ${RUN_URL:-}"
# Start the job line's value in the column of the URL above it.
padding="$(printf '%*s' "$(( ${#status} + 2 - 4 ))" '')"
job_line="JOB:${padding}${workflow_name}"
tag="autogenerated:github"
if [[ -n "${workflow_file}" ]]; then
  job_line+=" [${workflow_file}]"
  tag+=":${workflow_file}"
fi

head="${status_line}"$'\n'"${job_line}"
if [[ -n "${message}" ]]; then
  head+=$'\n\n'"${message}"
fi
tail=""
if [[ -n "${trailers}" ]]; then
  tail=$'\n\n'"${trailers}"
fi
if (( ${#head} + ${#tail} > MAX_REVIEW_BYTES )); then
  fail "Refusing to post the review: with the message and trailers it" \
    "takes $(( ${#head} + ${#tail} )) bytes, exceeding the" \
    "${MAX_REVIEW_BYTES}-byte limit"
fi

# The items come from failed-jobs.py, which already made each one a
# single line without control characters; anything else is dropped.
items=()
more=0
if [[ "${report_annotations}" == "true" ]] \
  && [[ "${status}" == "FAILURE" || "${status}" == "CANCELLED" ]]; then
  while IFS= read -r line; do
    if [[ "${line}" != "- "* ]] || has_control "${line}"; then
      continue
    fi
    if [[ "${line}" =~ ^-\ \.\.\.\ and\ ([1-9][0-9]{0,5})\ more$ ]]; then
      more=$(( more + BASH_REMATCH[1] ))
    else
      items+=("${line}")
    fi
  done <<< "${ERROR_ITEMS:-}"
fi
if (( ${#items[@]} > MAX_ERROR_ITEMS )); then
  more=$(( more + ${#items[@]} - MAX_ERROR_ITEMS ))
  items=("${items[@]:0:MAX_ERROR_ITEMS}")
fi

# Drop items, counting them in the last line, until the block fits.
errors=""
budget=$(( MAX_REVIEW_BYTES - ${#head} - ${#tail} - 2 ))
while (( ${#items[@]} > 0 || more > 0 )); do
  errors="ERRORS:"
  for item in "${items[@]}"; do
    errors+=$'\n'"${item}"
  done
  if (( more > 0 )); then
    errors+=$'\n'"- ... and ${more} more"
  fi
  if (( ${#errors} <= budget )); then
    break
  fi
  errors=""
  if (( ${#items[@]} == 0 )); then
    break
  fi
  unset 'items[-1]'
  more=$(( more + 1 ))
done

comment="${head}"
if [[ -n "${errors}" ]]; then
  comment+=$'\n\n'"${errors}"
fi
comment+="${tail}"

review="gerrit review ${change},${patchset} --message $(quote "${comment}")"
if [[ "${COMMENT_ONLY:-}" == "false" ]]; then
  review+=" ${labels}"
fi
review+=" --tag ${tag}"
printf '%s\n' "${review}"
