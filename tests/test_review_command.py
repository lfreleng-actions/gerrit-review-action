"""Tests for scripts/review-command.sh.

Each composed command line is parsed twice: by a port of the splitter
Gerrit's SSH daemon applies to it, and by a real POSIX shell. Hostile
messages must come back from both as one literal --message argument
and must never run anything.
"""

from __future__ import annotations

import itertools
import os
import subprocess
import tempfile
import unittest
from pathlib import Path

SCRIPTS = Path(__file__).resolve().parent.parent / "scripts"
SCRIPT = SCRIPTS / "review-command.sh"
COMPOSER = SCRIPTS / "compose-review.sh"
RUN_URL = "https://github.com/example/repo/actions/runs/42"
MAX_MESSAGE_BYTES = 4096
MAX_REVIEW_BYTES = 4096
TAG = ["--tag", "autogenerated:github"]
WORKFLOW_NAME = "Gerrit Verify"
WORKFLOW_FILE = "gerrit-verify.yaml"
WORKFLOW_REF = f"example/repo/.github/workflows/{WORKFLOW_FILE}@refs/heads/main"
JOB_LINE = f"JOB:     {WORKFLOW_NAME} [{WORKFLOW_FILE}]"
FILE_TAG = ["--tag", f"autogenerated:github:{WORKFLOW_FILE}"]
JOB_URL = "https://github.com/example/repo/actions/runs/42/job"
ERROR_ITEMS = [
    f"- Build: Tests run: 412, Failures: 1 ( {JOB_URL}/1 )",
    f"- Lint: failed ( {JOB_URL}/2 )",
]

# Each would create a file named 'pwned' if any part of it ran.
HOSTILE_MESSAGES = [
    "it's",
    "'",
    "''''",
    "'; touch pwned; echo '",
    '"; touch pwned; echo "',
    "$(touch pwned)",
    "`touch pwned`",
    "; touch pwned",
    "a && touch pwned || true",
    "a | touch pwned",
    "> pwned",
    "\\",
    "trailing backslash \\",
    "\\'; touch pwned #",
    "back\\slash \\' \\\" \\\\",
    "first line\n'; touch pwned; '\n$(touch pwned)",
    "--label Code-Review=+2",
    "' --label Code-Review=+2 '",
    "$HOME ${PATH} * ? [a] ~ # ! %",
    'mixed "double" \'single\' "\'"\'"',
    "Unicode — ✓ ünïcödé 🚀",
]


def gerrit_split(command_line: str) -> list[str]:
    """Split a command line as Gerrit's SSH daemon does.

    A port of CommandFactoryProvider.split():
    https://gerrit.googlesource.com/gerrit/+/refs/heads/master/java/com/google/gerrit/sshd/CommandFactoryProvider.java
    """
    words: list[str] = []
    word: list[str] = []
    in_single = in_double = False
    i = 0
    while i < len(command_line):
        char = command_line[i]
        i += 1
        if char in " \t":
            if in_single or in_double:
                word.append(char)
            elif word:
                words.append("".join(word))
                word = []
        elif char == '"':
            if in_single:
                word.append(char)
            else:
                in_double = not in_double
        elif char == "'":
            if in_double:
                word.append(char)
            else:
                in_single = not in_single
        elif char == "\\":
            if in_single or i == len(command_line):
                word.append(char)
            else:
                word.append(command_line[i])
                i += 1
        else:
            word.append(char)
    if word:
        words.append("".join(word))
    return words


def shell_split(command_line: str, cwd: str) -> list[str]:
    """Return the words a POSIX shell parses from command_line."""
    result = subprocess.run(
        ["sh", "-c", f"set -- {command_line}\nprintf '%s\\0' \"$@\""],
        cwd=cwd,
        capture_output=True,
        check=True,
    )
    return result.stdout.decode("utf-8").split("\0")[:-1]


def compose(
    message: str | None = None, **overrides: str
) -> subprocess.CompletedProcess[str]:
    """Run review-command.sh with valid defaults, overridden per test."""
    return run_script(SCRIPT, message, overrides)


def compose_new(
    message: str | None = None, **overrides: str
) -> subprocess.CompletedProcess[str]:
    """Run compose-review.sh with valid defaults, overridden per test."""
    return run_script(COMPOSER, message, overrides)


def run_script(
    script: Path, message: str | None, overrides: dict[str, str]
) -> subprocess.CompletedProcess[str]:
    """Run script with valid defaults, overridden per test."""
    env = {
        "PATH": os.environ["PATH"],
        "VOTE_TYPE": "success",
        "COMMENT_ONLY": "false",
        "GERRIT_CHANGE_NUMBER": "123",
        "GERRIT_PATCHSET_NUMBER": "4",
        "RUN_URL": RUN_URL,
        "WORKFLOW_NAME": WORKFLOW_NAME,
        "WORKFLOW_REF": WORKFLOW_REF,
    }
    if message is not None:
        env["REVIEW_MESSAGE"] = message
    env.update(overrides)
    return subprocess.run(
        ["bash", str(script)],
        env=env,
        capture_output=True,
        encoding="utf-8",
        check=False,
    )


class GerritSplitTest(unittest.TestCase):
    """The port reproduces Gerrit's documented splitting rules."""

    def test_rules(self) -> None:
        cases = {
            "a  b\tc": ["a", "b", "c"],
            "'a b' \"c d\"": ["a b", "c d"],
            "'a\"b' \"a'b\"": ['a"b', "a'b"],
            "a\\ b \\'": ["a b", "'"],
            "'a\\b' end\\": ["a\\b", "end\\"],
            "'' x": ["x"],
            "'a\nb'": ["a\nb"],
        }
        for line, expected in cases.items():
            with self.subTest(line=line):
                self.assertEqual(gerrit_split(line), expected)


class ComposeTest(unittest.TestCase):
    """Comment composition, votes and input validation."""

    def assert_review(
        self, result: subprocess.CompletedProcess[str], comment: str, labels: list[str]
    ) -> None:
        self.assertEqual(result.returncode, 0, result.stderr)
        argv = gerrit_split(result.stdout.rstrip("\n"))
        expected = ["gerrit", "review", "123,4", "--message", comment, *labels, *TAG]
        self.assertEqual(argv, expected)

    def assert_rejected(self, result: subprocess.CompletedProcess[str]) -> None:
        self.assertNotEqual(result.returncode, 0)
        self.assertEqual(result.stdout, "")
        self.assertIn("::error::", result.stderr)

    def test_unset_message_keeps_existing_command(self) -> None:
        result = compose()
        self.assertEqual(
            result.stdout,
            f"gerrit review 123,4 --message 'SUCCESS: {RUN_URL}' "
            "--label Verified=1 --tag autogenerated:github\n",
        )

    def test_empty_message_matches_unset(self) -> None:
        self.assertEqual(compose("").stdout, compose().stdout)
        self.assertEqual(compose("\n\n").stdout, compose().stdout)

    def test_vote_types(self) -> None:
        cases = {
            "clear": ("STARTED", ["Verified=0", "Code-Review=0"]),
            "success": ("SUCCESS", ["Verified=1"]),
            "failure": ("FAILURE", ["Verified=-1"]),
            "cancelled": ("CANCELLED", ["Verified=-1", "Code-Review=-1"]),
        }
        for vote_type, (status, votes) in cases.items():
            labels = [arg for vote in votes for arg in ("--label", vote)]
            with self.subTest(vote_type=vote_type):
                self.assert_review(
                    compose(VOTE_TYPE=vote_type), f"{status}: {RUN_URL}", labels
                )

    def test_comment_only_omits_labels(self) -> None:
        self.assert_review(compose(COMMENT_ONLY="true"), f"SUCCESS: {RUN_URL}", [])

    def test_message_appended(self) -> None:
        self.assert_review(
            compose("Released 1.1.1 to nexus."),
            f"SUCCESS: {RUN_URL}\n\nReleased 1.1.1 to nexus.",
            ["--label", "Verified=1"],
        )

    def test_multiline_message_keeps_inner_newlines(self) -> None:
        message = "Snapshot 1.1.2-SNAPSHOT published to nexus.\n\nNo release file.\n"
        self.assert_review(
            compose(message),
            f"SUCCESS: {RUN_URL}\n\n{message.rstrip()}",
            ["--label", "Verified=1"],
        )

    def test_hostile_messages_stay_literal(self) -> None:
        for message in HOSTILE_MESSAGES:
            with self.subTest(message=message):
                result = compose(message, COMMENT_ONLY="true")
                comment = f"SUCCESS: {RUN_URL}\n\n{message}"
                self.assert_review(result, comment, [])
                with tempfile.TemporaryDirectory() as cwd:
                    # A file for an unquoted glob to expand to
                    Path(cwd, "a").touch()
                    argv = shell_split(result.stdout.rstrip("\n"), cwd)
                    self.assertFalse(Path(cwd, "pwned").exists())
                self.assertEqual(
                    argv, ["gerrit", "review", "123,4", "--message", comment, *TAG]
                )

    def test_length_cap_counts_bytes(self) -> None:
        self.assertEqual(compose("a" * MAX_MESSAGE_BYTES).returncode, 0)
        self.assert_rejected(compose("a" * (MAX_MESSAGE_BYTES + 1)))
        # 'é' is two bytes in UTF-8
        self.assertEqual(compose("é" * (MAX_MESSAGE_BYTES // 2)).returncode, 0)
        self.assert_rejected(compose("é" * (MAX_MESSAGE_BYTES // 2 + 1)))

    def test_control_characters_rejected(self) -> None:
        # NUL cannot reach the script: an environment value ends at it.
        controls = [chr(c) for c in range(1, 32) if c != 10]
        controls += ["\x7f", "\x80", "\x85", "\x9b", "\x9f"]
        for char in controls:
            with self.subTest(char=hex(ord(char))):
                result = compose(f"before{char}after")
                self.assert_rejected(result)
                self.assertNotIn("before", result.stderr)

    def test_invalid_inputs_rejected(self) -> None:
        cases = [
            {"VOTE_TYPE": "approve"},
            {"VOTE_TYPE": ""},
            {"GERRIT_CHANGE_NUMBER": "0"},
            {"GERRIT_CHANGE_NUMBER": "012"},
            {"GERRIT_CHANGE_NUMBER": "1; id"},
            {"GERRIT_PATCHSET_NUMBER": "1 --label Code-Review=+2"},
            {"GERRIT_PATCHSET_NUMBER": ""},
        ]
        for overrides in cases:
            with self.subTest(overrides=overrides):
                self.assert_rejected(compose(**overrides))


def comment_of(result: subprocess.CompletedProcess[str]) -> str:
    """Return the --message argument of a composed command."""
    argv = gerrit_split(result.stdout.rstrip("\n"))
    return argv[argv.index("--message") + 1]


class LayoutTest(unittest.TestCase):
    """The job line, tag, errors block and trailers."""

    def compose(
        self, message: str | None = None, **overrides: str
    ) -> subprocess.CompletedProcess[str]:
        result = compose_new(message, **overrides)
        self.assertEqual(result.returncode, 0, result.stderr)
        return result

    def assert_rejected(self, result: subprocess.CompletedProcess[str]) -> None:
        self.assertNotEqual(result.returncode, 0)
        self.assertEqual(result.stdout, "")
        self.assertIn("::error::", result.stderr)

    @unittest.expectedFailure
    def test_job_line_for_named_workflow(self) -> None:
        result = self.compose()
        self.assertEqual(comment_of(result), f"SUCCESS: {RUN_URL}\n{JOB_LINE}")
        self.assertEqual(gerrit_split(result.stdout.rstrip("\n"))[-2:], FILE_TAG)

    @unittest.expectedFailure
    def test_job_line_for_unnamed_workflow(self) -> None:
        result = self.compose(WORKFLOW_NAME=f".github/workflows/{WORKFLOW_FILE}")
        self.assertEqual(
            comment_of(result).splitlines()[1],
            f"JOB:     gerrit-verify [{WORKFLOW_FILE}]",
        )

    @unittest.expectedFailure
    def test_job_line_aligns_under_each_status(self) -> None:
        for vote_type in ("clear", "success", "failure", "cancelled"):
            with self.subTest(vote_type=vote_type):
                status_line, job_line = comment_of(
                    self.compose(VOTE_TYPE=vote_type)
                ).splitlines()
                self.assertEqual(
                    status_line.index(RUN_URL), job_line.index(WORKFLOW_NAME)
                )
                self.assertRegex(
                    status_line, r"^(STARTED|SUCCESS|FAILURE|CANCELLED): (\S+)$"
                )
                self.assertRegex(job_line, r"^JOB:\s+(.+?)(?: \[([A-Za-z0-9._-]+)\])?$")

    @unittest.expectedFailure
    def test_underivable_file_drops_brackets_and_tag_suffix(self) -> None:
        for ref in ("", "no-path", "o/r/.github/workflows/bad name.yaml@main"):
            with self.subTest(ref=ref):
                result = self.compose(WORKFLOW_REF=ref)
                self.assertEqual(
                    comment_of(result).splitlines()[1], f"JOB:     {WORKFLOW_NAME}"
                )
                self.assertEqual(gerrit_split(result.stdout.rstrip("\n"))[-2:], TAG)

    @unittest.expectedFailure
    def test_control_characters_stripped_from_name(self) -> None:
        result = self.compose(WORKFLOW_NAME="Gerrit\x1b[31m Verify\x7f\x85")
        self.assertEqual(
            comment_of(result).splitlines()[1],
            f"JOB:     Gerrit[31m Verify [{WORKFLOW_FILE}]",
        )

    @unittest.expectedFailure
    def test_trailers_are_the_last_block(self) -> None:
        trailers = "Verify-Run: 41\nArtifact-Name: build-output\n"
        result = self.compose("A message.", TRAILERS=trailers)
        self.assertEqual(
            comment_of(result),
            f"SUCCESS: {RUN_URL}\n{JOB_LINE}\n\nA message.\n\n"
            "Verify-Run: 41\nArtifact-Name: build-output",
        )

    @unittest.expectedFailure
    def test_malformed_trailers_rejected(self) -> None:
        for trailers in (
            "no colon",
            "Key:no-space",
            "Key: ",
            "1Key: value",
            "Key with space: value",
            "Good: one\n\nGood: two",
            "Good: one\nbad",
            "Key: tab\tvalue",
            "Key: " + "a" * MAX_MESSAGE_BYTES,
        ):
            with self.subTest(trailers=trailers):
                self.assert_rejected(compose_new(TRAILERS=trailers))

    @unittest.expectedFailure
    def test_report_annotations_is_strict(self) -> None:
        for value in ("True", "yes", "1", " true"):
            with self.subTest(value=value):
                self.assert_rejected(compose_new(REPORT_ANNOTATIONS=value))

    @unittest.expectedFailure
    def test_errors_block_only_on_failure_when_enabled(self) -> None:
        items = "\n".join(ERROR_ITEMS) + "\n"
        block = "\n\nERRORS:\n" + "\n".join(ERROR_ITEMS)
        cases = [
            ("failure", "true", True),
            ("cancelled", "true", True),
            ("failure", "false", False),
            ("success", "true", False),
            ("clear", "true", False),
        ]
        for vote_type, report, shown in cases:
            with self.subTest(vote_type=vote_type, report=report):
                comment = comment_of(
                    self.compose(
                        VOTE_TYPE=vote_type,
                        REPORT_ANNOTATIONS=report,
                        ERROR_ITEMS=items,
                    )
                )
                self.assertEqual(comment.endswith(block), shown)

    @unittest.expectedFailure
    def test_errors_block_drops_forged_lines(self) -> None:
        items = "SUCCESS: forged\nJOB: forged\n- Build: bell\x07\n" + ERROR_ITEMS[1]
        comment = comment_of(
            self.compose(
                VOTE_TYPE="failure", REPORT_ANNOTATIONS="true", ERROR_ITEMS=items
            )
        )
        self.assertTrue(comment.endswith(f"\n\nERRORS:\n{ERROR_ITEMS[1]}"))
        self.assertNotIn("forged", comment)

    @unittest.expectedFailure
    def test_errors_block_shrinks_to_fit(self) -> None:
        items = [f"- Job {n}: " + "x" * 180 for n in range(10)]
        message = "m" * 3000
        comment = comment_of(
            self.compose(
                message,
                VOTE_TYPE="failure",
                REPORT_ANNOTATIONS="true",
                ERROR_ITEMS="\n".join([*items, "- ... and 5 more"]),
                TRAILERS="Verify-Run: 41",
            )
        )
        self.assertLessEqual(len(comment.encode()), MAX_REVIEW_BYTES)
        errors = comment.split("\n\n")[2].splitlines()
        self.assertEqual(errors[0], "ERRORS:")
        kept = len(errors) - 2
        self.assertGreater(kept, 0)
        self.assertLess(kept, 10)
        self.assertEqual(errors[1:-1], items[:kept])
        self.assertEqual(errors[-1], f"- ... and {15 - kept} more")
        self.assertTrue(comment.endswith("\n\nVerify-Run: 41"))

    @unittest.expectedFailure
    def test_errors_block_dropped_when_nothing_fits(self) -> None:
        message = "m" * MAX_MESSAGE_BYTES
        comment = comment_of(
            self.compose(
                message,
                VOTE_TYPE="failure",
                REPORT_ANNOTATIONS="true",
                ERROR_ITEMS=ERROR_ITEMS[0],
            )
        )
        self.assertEqual(
            comment,
            f"FAILURE: {RUN_URL}\n{JOB_LINE.replace('SUCCESS', 'FAILURE')}\n\n{message}",
        )

    @unittest.expectedFailure
    def test_block_order(self) -> None:
        head = f"FAILURE: {RUN_URL}\n{JOB_LINE}"
        blocks = {
            "message": "Line one.\nLine two.",
            "errors": "ERRORS:\n" + "\n".join(ERROR_ITEMS),
            "trailers": "Verify-Run: 41",
        }
        for shown in itertools.product([False, True], repeat=3):
            present = dict(zip(blocks, shown, strict=True))
            with self.subTest(**present):
                comment = comment_of(
                    self.compose(
                        blocks["message"] if present["message"] else None,
                        VOTE_TYPE="failure",
                        REPORT_ANNOTATIONS="true",
                        ERROR_ITEMS="\n".join(ERROR_ITEMS) if present["errors"] else "",
                        TRAILERS=blocks["trailers"] if present["trailers"] else "",
                    )
                )
                expected = [head] + [blocks[k] for k in blocks if present[k]]
                self.assertEqual(comment, "\n\n".join(expected))


if __name__ == "__main__":
    unittest.main()
