"""Tests for scripts/send-review.sh.

A fake 'ssh' first on PATH replays a scripted exit status and stderr
for each call and records the arguments it received, so the tests see
every review the script sends without a Gerrit server.
"""

from __future__ import annotations

import os
import subprocess
import tempfile
import unittest
from pathlib import Path

SCRIPT = Path(__file__).resolve().parent.parent / "scripts" / "send-review.sh"
HOST = "gerrit.example.org"
RUN_URL = "https://github.com/example/repo/actions/runs/42"
REVIEW_COMMAND = (
    f"gerrit review 123,4 --message 'SUCCESS: {RUN_URL}' "
    "--label Verified=1 --tag autogenerated:github"
)
COMMENT_COMMAND = (
    f"gerrit review 123,4 --message 'SUCCESS: {RUN_URL}' --tag autogenerated:github"
)
CHANGE_IS_CLOSED = (
    "error: fatal: change is closed\n"
    "fatal: one or more reviews failed; review output above\n"
)
CANNOT_REDUCE_VOTE = (
    "error: fatal: Cannot reduce vote on labels for closed change: Verified\n"
)
PERMISSION_DENIED = "user@gerrit.example.org: Permission denied (publickey).\n"
WARNING = "::warning title=Change already closed::"

# Each call bumps a counter, records its arguments NUL-separated, then
# replays the stderr and exit status scripted for that call number.
FAKE_SSH = """#!/usr/bin/env bash
set -eu
dir="${FAKE_SSH_DIR}"
count=0
if [[ -f "${dir}/count" ]]; then
  count="$(cat "${dir}/count")"
fi
count=$((count + 1))
echo "${count}" > "${dir}/count"
printf '%s\\0' "$@" > "${dir}/args.${count}"
if [[ -f "${dir}/stderr.${count}" ]]; then
  cat "${dir}/stderr.${count}" >&2
fi
status=0
if [[ -f "${dir}/status.${count}" ]]; then
  status="$(cat "${dir}/status.${count}")"
fi
exit "${status}"
"""


class Sent:
    """The outcome of one run of the script."""

    def __init__(
        self,
        result: subprocess.CompletedProcess[str],
        calls: list[list[str]],
        outputs: dict[str, str],
    ) -> None:
        self.result = result
        self.calls = calls
        self.outputs = outputs


def send(responses: list[tuple[int, str]], **overrides: str) -> Sent:
    """Run the script against a fake ssh scripted with responses.

    Each response is the (exit status, stderr) of one ssh call, in
    order; calls beyond the list succeed silently.
    """
    with tempfile.TemporaryDirectory() as tmp:
        bin_dir = Path(tmp, "bin")
        state = Path(tmp, "state")
        bin_dir.mkdir()
        state.mkdir()
        fake = bin_dir / "ssh"
        fake.write_text(FAKE_SSH, encoding="utf-8")
        fake.chmod(0o755)
        for number, (status, stderr) in enumerate(responses, start=1):
            Path(state, f"status.{number}").write_text(str(status), encoding="utf-8")
            Path(state, f"stderr.{number}").write_text(stderr, encoding="utf-8")
        output = Path(tmp, "github_output")
        output.touch()
        env = {
            "PATH": f"{bin_dir}{os.pathsep}{os.environ['PATH']}",
            "FAKE_SSH_DIR": str(state),
            "GITHUB_OUTPUT": str(output),
            "TARGET_HOST": HOST,
            "REVIEW_COMMAND": REVIEW_COMMAND,
            "COMMENT_COMMAND": COMMENT_COMMAND,
            "COMMENT_ONLY": "false",
            "CLOSED_CHANGE": "warn",
            "GERRIT_CHANGE_NUMBER": "123",
            "GERRIT_PATCHSET_NUMBER": "4",
        }
        env.update(overrides)
        result = subprocess.run(
            ["bash", str(SCRIPT)],
            env=env,
            capture_output=True,
            encoding="utf-8",
            check=False,
        )
        calls = []
        for args in sorted(state.glob("args.*"), key=lambda p: int(p.suffix[1:])):
            calls.append(args.read_text(encoding="utf-8").split("\0")[:-1])
        outputs = {}
        for line in output.read_text(encoding="utf-8").splitlines():
            name, _, value = line.partition("=")
            outputs[name] = value
        return Sent(result, calls, outputs)


class SendReviewTest(unittest.TestCase):
    """Closed-change handling around the review sent over SSH."""

    def assert_closed_with_warning(self, sent: Sent) -> None:
        self.assertEqual(sent.result.returncode, 0, sent.result.stderr)
        self.assertEqual(sent.outputs, {"change-closed": "true"})
        warnings = [
            line for line in sent.result.stdout.splitlines() if line.startswith(WARNING)
        ]
        self.assertEqual(len(warnings), 1, sent.result.stdout)
        self.assertIn("change 123 patchset 4", warnings[0])

    def test_successful_review(self) -> None:
        sent = send([(0, "")])
        self.assertEqual(sent.result.returncode, 0, sent.result.stderr)
        self.assertEqual(sent.calls, [["--", HOST, REVIEW_COMMAND]])
        self.assertEqual(sent.outputs, {"change-closed": "false"})
        self.assertNotIn("::warning", sent.result.stdout)

    def test_change_is_closed_retries_as_comment(self) -> None:
        sent = send([(1, CHANGE_IS_CLOSED), (0, "")])
        self.assertEqual(
            sent.calls,
            [["--", HOST, REVIEW_COMMAND], ["--", HOST, COMMENT_COMMAND]],
        )
        self.assert_closed_with_warning(sent)
        self.assertIn("as a comment instead of a vote", sent.result.stdout)
        # Gerrit's reply still reaches the log
        self.assertIn("change is closed", sent.result.stderr)

    def test_cannot_reduce_vote_retries_as_comment(self) -> None:
        sent = send([(1, CANNOT_REDUCE_VOTE), (0, "")])
        self.assertEqual(
            sent.calls,
            [["--", HOST, REVIEW_COMMAND], ["--", HOST, COMMENT_COMMAND]],
        )
        self.assert_closed_with_warning(sent)
        self.assertIn("as a comment instead of a vote", sent.result.stdout)

    def test_match_ignores_case(self) -> None:
        sent = send([(1, "fatal: CHANGE IS CLOSED\n"), (0, "")])
        self.assertEqual(len(sent.calls), 2)
        self.assert_closed_with_warning(sent)

    def test_comment_only_review_is_not_retried(self) -> None:
        sent = send(
            [(1, CHANGE_IS_CLOSED)],
            COMMENT_ONLY="true",
            REVIEW_COMMAND=COMMENT_COMMAND,
        )
        self.assertEqual(sent.calls, [["--", HOST, COMMENT_COMMAND]])
        self.assert_closed_with_warning(sent)

    def test_failed_retry_still_warns(self) -> None:
        sent = send([(1, CHANGE_IS_CLOSED), (1, CHANGE_IS_CLOSED)])
        self.assertEqual(len(sent.calls), 2)
        self.assert_closed_with_warning(sent)
        self.assertIn("retry failed", sent.result.stdout)
        self.assertNotIn("as a comment instead of a vote", sent.result.stdout)

    def test_closed_change_with_fail_exits_non_zero(self) -> None:
        sent = send([(1, CHANGE_IS_CLOSED)], CLOSED_CHANGE="fail")
        self.assertNotEqual(sent.result.returncode, 0)
        self.assertEqual(sent.calls, [["--", HOST, REVIEW_COMMAND]])
        self.assertEqual(sent.outputs, {"change-closed": "true"})
        self.assertNotIn("::warning", sent.result.stdout)
        self.assertIn("change is closed", sent.result.stderr)

    def test_unrelated_failure_exits_non_zero(self) -> None:
        for setting in ("warn", "fail"):
            with self.subTest(closed_change=setting):
                sent = send([(255, PERMISSION_DENIED)], CLOSED_CHANGE=setting)
                self.assertEqual(sent.result.returncode, 255)
                self.assertEqual(sent.calls, [["--", HOST, REVIEW_COMMAND]])
                self.assertEqual(sent.outputs, {"change-closed": "false"})
                self.assertNotIn("::warning", sent.result.stdout)
                self.assertIn("Permission denied", sent.result.stderr)

    def test_invalid_closed_change_rejected_before_ssh(self) -> None:
        for setting in ("", "ignore", "Warn", "warn\n::warning::x"):
            with self.subTest(closed_change=setting):
                sent = send([], CLOSED_CHANGE=setting)
                self.assertNotEqual(sent.result.returncode, 0)
                self.assertEqual(sent.calls, [])
                self.assertIn("::error::", sent.result.stderr)


if __name__ == "__main__":
    unittest.main()
